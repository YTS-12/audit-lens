def from_ksic(code: str) -> str | None:
    """KSIC 코드 → 분류2. 가장 긴 접두 우선."""
    if not code:
        return None
    for n in range(len(code), 1, -1):
        hit = KSIC_TO_CLS2.get(code[:n])
        if hit:
            return hit
    return None


def from_krx(sector: str) -> str | None:
    """KRX 업종명 → 분류2(거친 폴백)."""
    s = (sector or "").strip()
    if not s:
        return None
    if s in KRX_TO_CLS2:
        return KRX_TO_CLS2[s]
    for k, v in KRX_TO_CLS2.items():
        if k in s or s in k:
            return v
    return None
